/* ไทย ← อังกฤษ สำหรับให้ผู้ใช้พิมพ์ชื่ออังกฤษในช่องค้นหาได้ */
const NAME_TH = {};
for (const [th, en] of Object.entries(NAME_EN))
    NAME_TH[en.toLowerCase()] = th;
/* ---- API ---- */
function t(key, p) {
    const dict = STR[PREFS.lang] || STR.th;
    let s = dict[key];
    if (s == null)
        s = (STR.th[key] != null ? STR.th[key] : key);
    if (p)
        for (const k in p)
            s = s.split("{" + k + "}").join(String(p[k]));
    return s;
}
/* ชื่อสถานี/สถานที่ตามภาษาปัจจุบัน */
function sname(th) {
    if (PREFS.lang === "en")
        return NAME_EN[th] || th;
    return th;
}
/* ชื่อสายตามภาษาปัจจุบัน */
function lname(lid) { return PREFS.lang === "en" ? (LINE_EN[lid] || LINES[lid].n) : LINES[lid].n; }
function ltag(lid) { return (PREFS.lang === "en" && TAG_EN[lid]) ? TAG_EN[lid] : LINES[lid].tag; }
/* ใส่ข้อความลงใน HTML ที่ทำ mark ไว้ด้วย data-i18n */
function applyStaticI18n(root) {
    const host = root || document;
    host.querySelectorAll("[data-i18n]").forEach(e => {
        e.textContent = t(e.getAttribute("data-i18n") || "");
    });
    host.querySelectorAll("[data-i18n-ph]").forEach(e => {
        e.placeholder = t(e.getAttribute("data-i18n-ph") || "");
    });
    host.querySelectorAll("[data-i18n-al]").forEach(e => {
        e.setAttribute("aria-label", t(e.getAttribute("data-i18n-al") || ""));
    });
    document.title = t("app.name");
}
